// scripts/export-mongo-to-d1.mjs
//
// One-shot export of the durable MongoDB collections into a SQL file that can
// be loaded into the Cloudflare D1 database:
//
//   npm run db:export
//   npx wrangler d1 execute sunoverthecloud-d1 --remote --file=scripts/seed-data.sql
//
// Only durable data is exported: users, favorites and password-reset tokens.
// The KV caches (geocoding results, day summaries) regenerate on demand.
// Mongo ObjectId strings are kept as the D1 TEXT ids so every favorite's
// `user_id` reference stays valid.
import fs from 'node:fs';
import path from 'node:path';
import dotenv from 'dotenv';
import { MongoClient } from 'mongodb';

dotenv.config({ path: '.env.local' });
dotenv.config();

const {
  MONGODB_ATLAS_USERNAME,
  MONGODB_ATLAS_PASSWORD,
  MONGODB_ATLAS_CLUSTER_URL,
  MONGODB_ATLAS_DB_NAME,
  MONGODB_ATLAS_APP_NAME,
} = process.env;

if (
  !MONGODB_ATLAS_USERNAME ||
  !MONGODB_ATLAS_PASSWORD ||
  !MONGODB_ATLAS_CLUSTER_URL ||
  !MONGODB_ATLAS_DB_NAME
) {
  console.error('Missing MongoDB environment variables (MONGODB_ATLAS_*). Aborting.');
  process.exit(1);
}

const uri = `mongodb+srv://${MONGODB_ATLAS_USERNAME}:${MONGODB_ATLAS_PASSWORD}@${MONGODB_ATLAS_CLUSTER_URL}/${MONGODB_ATLAS_DB_NAME}?retryWrites=true&w=majority&appName=${MONGODB_ATLAS_APP_NAME}`;

const OUTPUT_FILE = path.join('scripts', 'seed-data.sql');

const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (value instanceof Date) return String(value.getTime());
  if (typeof value === 'object' && typeof value.toString === 'function') {
    // ObjectId and other BSON wrappers.
    return sqlValue(value.toString());
  }
  return `'${String(value).replace(/'/g, "''")}'`;
};

const client = new MongoClient(uri);

try {
  await client.connect();
  const db = client.db(MONGODB_ATLAS_DB_NAME);

  const [users, favorites, tokens] = await Promise.all([
    db.collection('Users').find({}).toArray(),
    db.collection('UserFavorites').find({}).toArray(),
    db.collection('UserPasswordResetTokens').find({}).toArray(),
  ]);

  const lines = [
    '-- Generated by scripts/export-mongo-to-d1.mjs. Do not commit (contains user data).',
    'BEGIN TRANSACTION;',
  ];

  for (const user of users) {
    lines.push(
      'INSERT OR REPLACE INTO users (id, username, email, hashed_password, created_at) VALUES (' +
        [user._id, user.username, user.email, user.hashed_password, user.created_at]
          .map(sqlValue)
          .join(', ') +
        ');'
    );
  }

  for (const favorite of favorites) {
    lines.push(
      'INSERT OR REPLACE INTO user_favorites (id, user_id, location_name, longitude, latitude, country_code, sort_order) VALUES (' +
        [
          favorite._id,
          favorite.user_id,
          favorite.location_name,
          favorite.longitude,
          favorite.latitude,
          favorite.country_code,
          favorite.order ?? 0,
        ]
          .map(sqlValue)
          .join(', ') +
        ');'
    );
  }

  for (const token of tokens) {
    lines.push(
      'INSERT OR REPLACE INTO password_reset_tokens (id, user_id, token, created_at, expires_at) VALUES (' +
        [token._id, token.user_id, token.token, token.created_at, token.expires_at]
          .map(sqlValue)
          .join(', ') +
        ');'
    );
  }

  lines.push('COMMIT;');

  fs.writeFileSync(OUTPUT_FILE, lines.join('\n') + '\n');
  console.log(
    `Exported ${users.length} users, ${favorites.length} favorites and ${tokens.length} reset tokens to ${OUTPUT_FILE}`
  );
  console.log(
    `Load it with: npx wrangler d1 execute sunoverthecloud-d1 --remote --file=${OUTPUT_FILE}`
  );
} catch (err) {
  console.error('Export failed:', err);
  process.exitCode = 1;
} finally {
  await client.close().catch(() => {});
}
